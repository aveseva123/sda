// Generates sw-manifest.js: the precache list for sw.js and a content hash used as the cache version.
// Included: index.html, target.html, target.svg, manifest.webmanifest, styles.css, src/**/*.js,
// vendor/opencv.js, icons/*. Excluded: tests/, tools/, docs/, node_modules/, .git/, sw.js, sw-manifest.js.
// Usage: node tools/gen-sw-manifest.mjs
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const EXCLUDE_DIRS = new Set(['tests', 'tools', 'docs', 'node_modules', '.git', '.claude']);
const ROOT_FILES = ['index.html', 'target.html', 'target.svg', 'manifest.webmanifest', 'styles.css', 'vendor/opencv.js'];

function walk(dir, filter, out = []) {
  const abs = path.join(root, dir);
  if (!existsSync(abs)) return out;
  for (const name of readdirSync(abs).sort()) {
    const rel = dir ? `${dir}/${name}` : name;
    const st = statSync(path.join(root, rel));
    if (st.isDirectory()) { if (!EXCLUDE_DIRS.has(name)) walk(rel, filter, out); }
    else if (filter(rel, name)) out.push(rel);
  }
  return out;
}

export function collectFiles() {
  const files = new Set();
  for (const f of ROOT_FILES) if (existsSync(path.join(root, f))) files.add(f);
  for (const f of walk('src', (rel, name) => name.endsWith('.js'))) files.add(f);
  for (const f of walk('icons', (rel, name) => /\.(png|svg|ico|webp|jpg)$/i.test(name))) files.add(f);
  return Array.from(files).filter((f) => f !== 'sw.js' && f !== 'sw-manifest.js').sort();
}

export function buildManifest() {
  const files = collectFiles();
  const hash = createHash('sha1');
  for (const f of files) {
    hash.update(f); hash.update('\0');
    hash.update(readFileSync(path.join(root, f)));
    hash.update('\0');
  }
  const version = hash.digest('hex').slice(0, 12);
  const urls = files.map((f) => './' + f.split(path.sep).join('/'));
  const body = `// Generated by tools/gen-sw-manifest.mjs — do not edit by hand.\n` +
    `self.__VERSION = ${JSON.stringify(version)};\n` +
    `self.__PRECACHE = [\n${urls.map((u) => `  ${JSON.stringify(u)},`).join('\n')}\n];\n`;
  return { version, urls, body };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const { version, urls, body } = buildManifest();
  writeFileSync(path.join(root, 'sw-manifest.js'), body, 'utf8');
  console.log(`wrote sw-manifest.js: version ${version}, ${urls.length} files`);
}
