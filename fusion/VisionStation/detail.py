def build_ducts(ctx, parent, P, L):
    c = new_component(parent, 'Кабель-каналы (крышки сняты)')
    t = 1.5
    for name, (x0, x1, y0, y1, z0, z1) in DUCT.items():
        w, d, h = x1 - x0, y1 - y0, z1 - z0
        if name in ('D1', 'D2', 'D6'):                          # лежат на плите, открыты вверх
            box(c, (x0, y0, z0), (x1, y1, z0 + t), 'Кабель-канал %s %g×%g — дно' % (name, w, h))
            box(c, (x0, y0, z0), (x0 + t, y1, z1), 'Кабель-канал %s — стенка' % name)
            box(c, (x1 - t, y0, z0), (x1, y1, z1), 'Кабель-канал %s — стенка' % name)
            if name == 'D2':
                box(c, (x0, y0, z0), (x1, y0 + t, z1), 'Кабель-канал %s — борт' % name)
                box(c, (x0, y1 - t, z0), (x1, y1, z1), 'Кабель-канал %s — борт' % name)
            if name == 'D6':
                box(c, (x0, y0, z0), (x1, y0 + t, z1), 'Кабель-канал %s — борт' % name)
                box(c, (x0, y1 - t, z0), (x1, y1, z1), 'Кабель-канал %s — борт' % name)
            if name == 'D1':
                box(c, (x0, y0, z0), (x1, y0 + t, z1), 'Кабель-канал %s — торец' % name)
        elif name == 'D3':                                       # вертикальный за кромкой плиты, открыт назад (+Y)
            box(c, (x0, y0, z0), (x1, y0 + t, z1), 'Кабель-канал %s %g×%g — дно' % (name, w, d))
            box(c, (x0, y0, z0), (x0 + t, y1, z1), 'Кабель-канал %s — стенка' % name)
            box(c, (x1 - t, y0, z0), (x1, y1, z1), 'Кабель-канал %s — стенка' % name)
        else:                                                    # на стенке капота, открыт наружу (+Y)
            box(c, (x0, y0, z0), (x1, y0 + t, z1), 'Кабель-канал %s %g×%g — дно' % (name, w, d))
            if name == 'D4':
                box(c, (x0, y0, z0), (x0 + t, y1, z1), 'Кабель-канал %s — стенка' % name)
                box(c, (x1 - t, y0, z0), (x1, y1, z1), 'Кабель-канал %s — стенка' % name)
            else:
                box(c, (x0, y0, z0), (x1, y1, z0 + t), 'Кабель-канал %s — стенка' % name)
                box(c, (x0, y0, z1 - t), (x1, y1, z1), 'Кабель-канал %s — стенка' % name)
    # отверстие-проход в стенке капота для подсветки показано втулкой
    cylinder(c, 'y', (505, L['z_belt_top'] + 150), 4, P['hood_y'] / 2 - 4, P['hood_y'] / 2 + 1, 'Втулка прохода кабеля подсветки')
    return c


