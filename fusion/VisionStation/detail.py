# ---------- вспомогательные фигуры ----------
def belt_outline(c1, r1, c2, r2, n=18):
    """Контур ремня/ленты, огибающего две окружности (u, v) радиусов r1, r2 (внешние касательные)."""
    dx, dy = c2[0] - c1[0], c2[1] - c1[1]
    d = math.hypot(dx, dy)
    th = math.atan2(dy, dx)
    al = math.acos((r1 - r2) / d)
    pts = []
    # дуга на окружности 1: от th+al до th-al через th+pi (дальняя сторона)
    a0, a1 = th + al, th - al + 2 * math.pi
    for i in range(n + 1):
        a = a0 + (a1 - a0) * i / n
        pts.append((c1[0] + r1 * math.cos(a), c1[1] + r1 * math.sin(a)))
    # дуга на окружности 2: от th-al до th+al через th (ближняя сторона)
    a0, a1 = th - al, th + al
    for i in range(n + 1):
        a = a0 + (a1 - a0) * i / n
        pts.append((c2[0] + r2 * math.cos(a), c2[1] + r2 * math.sin(a)))
    return pts


def hex_bolt(c, axis, uv, d, length, a_head, name, direction=1):
    """Болт с шестигранной головкой: головка от a_head в сторону -direction, стержень от a_head на length в +direction."""
    k = 0.65 * d
    head = prism(c, axis, uv, 6, 0.95 * d, a_head - direction * k, a_head, name)
    body = head.bodies.item(0)
    cylinder_join(c, axis, uv, d / 2.0, a_head, a_head + direction * length, body)
    return head


def cable(c, pts, r, name):
    return tube_path(c, pts, r, name)


# ---------- лента кольцом и ремень GT2 ----------
def build_belt_loop(ctx, parent, P, L):
    c = new_component(parent, 'Лента ПВХ (кольцо)')
    za, rr, bw, t = L['z_axle'], P['roller_d'] / 2.0, P['belt_w'], P['belt_t']
    outer = belt_outline((0, za), rr + t, (P['belt_len'], za), rr + t, 24)
    inner = belt_outline((0, za), rr, (P['belt_len'], za), rr, 24)
    f = poly_prism(c, 'y', outer, -bw / 2, bw / 2, 'Лента ПВХ %g×%g бесконечная — кольцо вокруг роликов' % (bw, t))
    poly_prism(c, 'y', inner, -bw / 2 - 1, bw / 2 + 1, None, CUT, [f.bodies.item(0)])
    # ремень GT2 между шкивами
    y_out = bw / 2 + 10 + P['side_t']
    xm, zm = P['belt_len'] - 120, za - 110
    r1, r2 = P['pulley_small_d'] / 2.0, P['pulley_big_d'] / 2.0
    y1, y2 = y_out + 5, y_out + 11
    g = poly_prism(c, 'y', belt_outline((xm, zm), r1 + 1.5, (P['belt_len'], za), r2 + 1.5, 20), y1, y2, 'Ремень GT2-6 замкнутый — чёрный')
    poly_prism(c, 'y', belt_outline((xm, zm), r1, (P['belt_len'], za), r2, 20), y1 - 1, y2 + 1, None, CUT, [g.bodies.item(0)])
    return c


