// Help screen: static, scannable Russian guide for workshop users.
import { h, section, bigButton } from './components.js';

export const title = 'Справка';

export const RULE_SAME_SURFACE = 'Мишень и детали должны лежать на одной поверхности. Деталь на стопке на 20 мм выше мишени измеряется с ошибкой в проценты.';
export const RULE_ONE_LAYER = 'Детали раскладывать в один слой с зазором 2–3 см. Перекрытые кромки алгоритм не видит.';

const HINTS = [
  ['Мишень не найдена', 'Положите мишень в кадр. Все четыре метки должны быть видны целиком, без бликов и пальцев.'],
  ['Видно только часть мишени', 'Отодвиньтесь или сдвиньте телефон, чтобы попали все четыре метки — иначе точность ниже.'],
  ['Наклон больше 35°', 'Держите телефон ровнее над столом — экраном параллельно поверхности.'],
  ['Мишень слишком мелкая', 'Подойдите ближе. Мишень должна занимать не меньше 5 % кадра.'],
  ['Смазано', 'Держите ровнее, кадр смазан. Обопритесь локтями, дождитесь фокуса, снимайте без движения.'],
  ['Пересвет / блики', 'Отвернитесь от окна, блики мешают. Выключите вспышку, уберите прямой свет с металла.'],
  ['Мишень читается плохо', 'Переснимите: протрите мишень, уберите тень от телефона, добавьте света.'],
  ['Слишком далеко', 'Подойдите ближе — на мишень должно приходиться больше пикселей.'],
  ['Детали не найдены', 'Детали должны быть тёмными на светлом фоне и лежать рядом с мишенью, внутри кадра.'],
];

function p(text) { return h('p', { style: { margin: '0' } }, text); }
function li(...children) { return h('li', { style: { margin: '0 0 8px' } }, ...children); }
function ol(...items) { return h('ol', { style: { margin: '0', paddingLeft: '24px' } }, ...items); }
function ul(...items) { return h('ul', { style: { margin: '0', paddingLeft: '24px' } }, ...items); }
function b(text) { return h('strong', {}, text); }

function rulesBox() {
  return h('div', { class: 'section', id: 'help-rules', style: { background: '#4a3410', border: '1px solid var(--warn)' } },
    h('h2', { class: 'section-title', style: { color: 'var(--warn)' } }, 'Два правила, которые нарушают чаще всего'),
    h('div', { style: { fontSize: '20px', fontWeight: '700', color: 'var(--text)' } }, '1. ' + RULE_SAME_SURFACE),
    h('div', { style: { fontSize: '20px', fontWeight: '700', color: 'var(--text)' } }, '2. ' + RULE_ONE_LAYER));
}

function hintsTable() {
  return h('div', { class: 'table-wrap' }, h('table', { class: 'table', id: 'help-hints' },
    h('thead', {}, h('tr', {}, h('th', {}, 'Подсказка на экране'), h('th', {}, 'Что делать'))),
    h('tbody', {}, HINTS.map(([hint, fix]) => h('tr', {}, h('td', { style: { fontWeight: '700', whiteSpace: 'nowrap' } }, hint), h('td', {}, fix))))));
}

export async function mount(root, ctx) {
  const page = h('div', { class: 'page', dataset: { view: 'help' } });

  page.appendChild(rulesBox());

  page.appendChild(section('Как это работает',
    p('Вы кладёте печатную мишень с четырьмя метками рядом с деталями и снимаете сверху. По меткам приложение узнаёт масштаб и перспективу кадра, выпрямляет фото в «вид сверху», находит тёмные детали на светлом фоне и измеряет их длину и ширину в миллиметрах. Затем размеры сверяются с раскроем DXF или таблицей заказа.'),
    p('Точность при хорошем кадре — около ±0,5–1 мм. Ошибка растёт с наклоном телефона, расстоянием до стола и при плохом освещении.')));

  page.appendChild(section('Мишень: печать и калибровка',
    ol(
      li('Откройте ', b('Ещё → Настройки → Печать мишени'), ' и распечатайте на A4 в масштабе ', b('100 %'), ' («реальный размер», без «подогнать под страницу»). Бумага матовая, не глянцевая.'),
      li('Измерьте линейкой контрольный отрезок ', b('«100 мм»'), ' на распечатке. Если получилось, например, 99,4 мм — введите это в ', b('Настройки → Мишень → Контрольный отрезок, факт'), '. Так компенсируется масштаб принтера.'),
      li('Наклейте мишень на жёсткую ровную основу (фанера, пластик) или заламинируйте матовой плёнкой. Мишень не должна гнуться и коробиться.'),
      li('Берегите метки: грязь, царапины и блики на чёрных квадратах мешают распознаванию. Лучше держать мишень в папке.')),
    p('Стандартная мишень: метки 40 мм, расстояние между центрами 130 × 210 мм. Если печатаете свою — введите её размеры в настройках.')));

  page.appendChild(section('Поправка на толщину',
    p('Камера видит верхнюю плоскость детали. Если деталь лежит выше мишени (на стопке, на листе), она кажется крупнее: при высоте съёмки 600 мм и превышении 20 мм ошибка около 3 %.'),
    ul(
      li(b('Самое простое и точное: '), 'положите мишень на такой же лист, что и детали, — на той же высоте. Поправка не нужна.'),
      li(b('Либо: '), 'в ', b('Настройки → Толщина партии'), ' введите толщину деталей и высоту съёмки (0 = высота считается автоматически по мишени). Размеры умножаются на (H − t) / H.'))));

  page.appendChild(section('Как снимать',
    ul(
      li('Светлый ровный фон: белая бумага, светлая фанера, крашеный стол. Тёмный металл на тёмном столе не найдётся.'),
      li('Телефон держите параллельно столу, основной камерой 1× (не широкоугольной). Наклон не больше 35°.'),
      li('Все четыре метки в кадре, мишень занимает не меньше 5 % кадра, детали — рядом с мишенью.'),
      li('Один слой, зазор между деталями 2–3 см, ничего не перекрывается, без инструмента и рук в кадре.'),
      li('Свет ровный, без прямого солнца и бликов на металле. Не заслоняйте лампу телефоном.'),
      li('Кнопка «Файл» позволяет снять штатной камерой телефона в полном разрешении — это точнее, чем кадр видео.'))));

  page.appendChild(section('Подсказки на экране камеры', hintsTable()));

  page.appendChild(section('Сценарий A — приёмка партии',
    ol(
      li('В разделе ', b('Заказы'), ' импортируйте раскрой DXF (или таблицу CSV/XLSX) и сделайте заказ текущим.'),
      li('На камере выберите режим ', b('«Приёмка партии»'), ' и проверьте, что выбран нужный заказ.'),
      li('Разложите детали в один слой рядом с мишенью, дождитесь подсказки «Можно снимать», снимите.'),
      li('На экране результата проверьте контуры; нажмите ', b('«Сверка с заказом»'), ' — увидите найдено / не хватает / лишнее.'),
      li('Если деталь опознана неверно — нажмите на неё и выберите позицию плана вручную. Экспортируйте CSV при необходимости.'))));

  page.appendChild(section('Сценарий B — одна деталь',
    ol(
      li('Режим ', b('«Одна деталь»'), ' на камере. Заказ выбирать не нужно — поиск идёт по всем заказам.'),
      li('Положите деталь рядом с мишенью и снимите.'),
      li('Приложение покажет размеры и ближайшую позицию плана: «Это деталь SHELF-04 из заказа …» или «Подходящей детали не найдено».'))));

  page.appendChild(section('Сценарий C — остаток',
    ol(
      li('Режим ', b('«Остаток»'), '. Положите обрезок листа на светлый фон рядом с мишенью и снимите.'),
      li('На результате нажмите на деталь → ', b('«Сохранить как остаток»'), '. Остаток получит номер вида R-019, размер, площадь и фото.'),
      li('В разделе ', b('Остатки'), ' введите размер нужной детали и нажмите ', b('«Найти»'), ' — покажутся остатки, из которых её можно вырезать, с учётом поворота и запаса на рез.'),
      li('Когда остаток пошёл в дело — отметьте его использованным и укажите, на что.'))));

  page.appendChild(section('Чего приложение НЕ делает',
    ul(
      li('Не определяет ', b('марку стали'), ' и состояние поверхности.'),
      li('Не измеряет ', b('толщину'), ' — только длину и ширину в плане. Толщину вводите вручную в заказе.'),
      li('Не работает ', b('без мишени'), ': без меток нет масштаба, размеры посчитать невозможно.'),
      li('Не видит перекрытые и стопкой лежащие детали, отверстия внутри детали в размер не входят.'))));

  page.appendChild(section('Офлайн и данные',
    p('Приложение работает без сети после первой загрузки — можно добавить его на главный экран телефона. Все заказы, замеры с фото и остатки хранятся только на этом устройстве.'),
    p('Резервная копия базы — в ', b('Настройки → Данные → Экспорт всей базы'), '. Восстановить или объединить данные с другого телефона — ', b('«Импорт базы»'), '.'),
    h('div', { class: 'btn-row' },
      bigButton('Настройки', () => ctx.navigate('#/settings'), { kind: 'secondary', icon: '⚙️' }),
      bigButton('К камере', () => ctx.navigate('#/camera'), { kind: 'primary', icon: '📷' }))));

  root.appendChild(page);
  return () => {};
}
